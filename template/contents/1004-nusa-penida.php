    <h1 class="text-4xl md:text-5xl font-extrabold mb-6 tracking-tight leading-tight">
      Nusa Penida: <span class="text-blue-400">Bali’s Wild and Beautiful Diving Frontier</span>
    </h1>

    <p class="text-lg md:text-xl text-gray-300 max-w-3xl mx-auto mb-8 leading-relaxed">
      Just a short boat ride from mainland Bali lies <strong>Nusa Penida</strong> — an island of towering cliffs, crystalline waters, and world-class dive sites.  
      It’s where raw nature meets ethereal beauty, and where divers come face-to-face with one of the ocean’s most majestic creatures: the <em>mola mola</em>.
    </p>

    <article class="text-left text-gray-200 text-lg md:text-xl leading-relaxed space-y-6 mb-12">
      <p>
        <strong>Nusa Penida</strong> isn’t just another diving destination — it’s an adventure in itself.  
        The journey begins with a thrilling fast-boat ride across the Badung Strait, where turquoise waves shimmer under the morning sun.  
        As you approach the island, limestone cliffs rise from the sea like ancient fortresses guarding Bali’s most pristine waters.
      </p>

      <p>
        <strong>Diving in Nusa Penida</strong> offers a unique mix of excitement and serenity.  
        The island is famous for <em>Manta Point</em>, where graceful manta rays glide effortlessly above divers, their wings spanning meters wide.  
        At <em>Crystal Bay</em>, visibility can reach 30 meters — and between July and October, the elusive <strong>mola mola</strong> (ocean sunfish) emerges from the deep, an encounter so surreal it feels like meeting a creature from another planet.
      </p>

      <p>
        Beneath the surface, <strong>Nusa Penida Bali</strong> reveals a vibrant tapestry of coral gardens, sea fans, and reef fish in dazzling colors.  
        The currents can be strong, making each dive an exhilarating dance with nature’s rhythm. But that’s what makes Penida unforgettable — it commands respect and rewards those who dive with awareness and awe.
      </p>

      <p>
        Beyond the reefs, life in Nusa Penida flows at a slower pace.  
        Small villages hug the cliffs, and from the hilltops, you can see the infinite blue stretching beyond the horizon.  
        When you’re not diving, explore <em>Kelingking Beach</em>, <em>Broken Beach</em>, or <em>Angel’s Billabong</em> — landscapes so cinematic they blur the line between dream and reality.
      </p>

      <p class="italic text-gray-400">
        For many divers, <strong>Nusa Penida</strong> isn’t just a dive site — it’s a calling.  
        A place where you rediscover humility in the vastness of the ocean and leave a part of your soul drifting with the currents of Bali’s deep blue frontier.
      </p>
    </article>

