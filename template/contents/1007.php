    <h1 class="text-4xl md:text-5xl font-extrabold mb-6 tracking-tight leading-tight">
      Padang Bai: <span class="text-blue-400">Where Bali’s Ocean Spirit Begins</span>
    </h1>

    <p class="text-lg md:text-xl text-gray-300 max-w-3xl mx-auto mb-8 leading-relaxed">
      In the heart of Bali’s eastern coastline, <strong>Padang Bai</strong> hums with life — fishermen mending nets, boats gliding toward distant islands, and beneath it all, a world of coral gardens waiting for curious eyes.  
      For divers, <em>Padang Bai</em> is more than a port — it’s a gateway to the extraordinary.
    </p>

    <article class="text-left text-gray-200 text-lg md:text-xl leading-relaxed space-y-6 mb-12">
      <p>
        Known as the main departure point to the Gili Islands, <strong>Padang Bai Bali</strong> hides some of the island’s most beautiful dive sites right at its doorstep.  
        The calm bay shelters vibrant reefs, dramatic slopes, and mysterious blue waters where both beginner and experienced divers can find magic beneath the surface.
      </p>

      <p>
        The famous <strong>Blue Lagoon</strong> is a dream for macro lovers — an underwater garden bursting with life.  
        Tiny frogfish, leaf scorpionfish, and nudibranchs hide among soft corals like jewels in a treasure chest.  
        A few minutes away, <em>Jetty</em> offers a darker, moodier dive, with volcanic pillars covered in anemones and sea fans swaying in slow rhythm.
      </p>

      <p>
        For adventure seekers, <strong>Padang Bai diving</strong> also leads to <em>Tanjung Jepun</em> and <em>Bias Tugel</em> — perfect for drift dives where currents carry you past kaleidoscopic walls of coral.  
        And when the tide and timing align, lucky divers may even meet turtles or reef sharks gliding in silent grace.
      </p>

      <p>
        Above the surface, Padang Bai is a fusion of tradition and travel — temple bells echo from the hills, incense drifts through the alleys, and the ocean glows at sunset.  
        It’s a place where you can dive in the morning, sip coffee by the shore, and watch ferries disappear toward Lombok as the stars rise over the water.
      </p>

      <p class="italic text-gray-400">
        In <strong>Padang Bai</strong>, the ocean doesn’t just surround you — it greets you.  
        Every wave carries a story, every dive a moment of connection, reminding you that Bali’s beauty begins right here, where land meets sea.
      </p>
    </article>

