    <h1 class="text-4xl md:text-5xl font-extrabold mb-6 tracking-tight leading-tight">
      Amed: <span class="text-blue-400">The Soul of Bali’s Eastern Coast</span>
    </h1>

    <p class="text-lg md:text-xl text-gray-300 max-w-3xl mx-auto mb-8 leading-relaxed">
      Along the tranquil shores of East Bali, <strong>Amed</strong> stretches like a quiet poem written in black volcanic sand.  
      Once a humble fishing village, it has become a sanctuary for travelers and divers seeking serenity, authenticity, and world-class underwater beauty.
    </p>

    <article class="text-left text-gray-200 text-lg md:text-xl leading-relaxed space-y-6 mb-12">
      <p>
        The road to <strong>Amed Bali</strong> winds through terraced rice fields, salt farms, and sleepy coastal towns.  
        As you arrive, the scent of the sea mingles with the smoky aroma of clove cigarettes and grilled fish.  
        Here, life slows down — and beneath the waves, another world awakens.
      </p>

      <p>
        <strong>Diving in Amed</strong> is gentle, colorful, and deeply intimate.  
        The reefs are alive with hard corals, nudibranchs, and shimmering schools of anthias.  
        You can begin your dive directly from the shore, slipping into warm water where lionfish and moray eels watch from their coral castles.
      </p>

      <p>
        One of Amed’s hidden treasures is the <strong>Japanese Wreck</strong> — a small ship resting in shallow water, now covered with vibrant coral and soft sponges.  
        Sunlight filters through the wreck, creating an ethereal dance of light and shadow.  
        For underwater photographers, it’s a dream — every frame feels alive.
      </p>

      <p>
        What sets <strong>Amed diving</strong> apart is its peaceful rhythm.  
        While <a href="https://balidiving.com/sites" class="text-blue-400 hover:underline">Nusa Penida</a> and <a href="https://balidiving.com/sites" class="text-blue-400 hover:underline">Tulamben</a> attract divers chasing big pelagics, Amed offers something subtler — the joy of slow exploration, the poetry of bubbles rising through coral gardens, and the quiet conversations between diver and sea.
      </p>

      <p>
        Beyond diving, Amed invites reflection.  
        Sunsets paint the horizon in molten gold while Mount Agung watches silently in the distance.  
        At night, the stars scatter across the sky like plankton glowing beneath the surface — a reminder that everything in Amed, above and below, is connected.
      </p>

      <p class="italic text-gray-400">
        Amed isn’t a place you just visit — it’s a place that stays with you.  
        In the hush of the waves, you’ll find the pulse of Bali’s soul.
      </p>
    </article>

