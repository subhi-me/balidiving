    <h1 class="text-4xl md:text-5xl font-extrabold mb-6 tracking-tight leading-tight">
      USAT Liberty Wreck: <span class="text-blue-400">Bali’s Most Iconic Underwater Treasure</span>
    </h1>
    <p class="text-lg md:text-xl text-gray-300 max-w-3xl mx-auto mb-8 leading-relaxed">
      The <strong>USAT Liberty Wreck</strong> in Tulamben, Bali, is more than just a dive site — it’s a living museum beneath the sea.  
      Resting gracefully on a black volcanic slope, this historic World War II cargo ship has become a paradise for divers, photographers, and marine life enthusiasts from around the world.
    </p>

    <article class="text-left text-gray-200 text-lg md:text-xl leading-relaxed space-y-6 mb-12">
      <p>
        Sunk by a Japanese torpedo in 1942, the <em>USAT Liberty</em> was originally a United States Army transport ship. After being towed to Tulamben, the vessel lay stranded until Mount Agung’s eruption in 1963 pushed it back into the ocean — where it now rests at a gentle slope between 5 and 30 meters deep.
      </p>

      <p>
        Today, the <strong>USAT Liberty Wreck</strong> stands as one of the most accessible wreck dives in the world. Divers can begin exploring directly from the shore — no boat needed.  
        The wreck’s skeletal structure is encrusted with soft corals, gorgonians, and sponges of every color imaginable, while schools of bumphead parrotfish, barracuda, and jackfish swirl through its corridors like living silver storms.
      </p>

      <p>
        Visibility is often excellent, ranging between 15–25 meters, and the calm conditions make it perfect for both beginners and advanced divers. Underwater photographers love the wreck’s dramatic silhouette, illuminated by shafts of tropical sunlight piercing through the openings. Each angle tells a story — part history, part art.
      </p>

      <p>
        For those interested in underwater heritage and marine ecology, a dive at the <strong>USAT Liberty Wreck Bali</strong> is not merely a recreational experience — it’s a spiritual one.  
        You’ll drift through time, feeling the quiet dignity of a ship that once carried soldiers, now reborn as a sanctuary for coral gardens and oceanic life.
      </p>

      <p class="italic text-gray-400">
        Whether you’re a seasoned diver or a curious traveler seeking your first underwater adventure, the USAT Liberty Wreck invites you to witness how history and nature intertwine in perfect harmony beneath the waves.
      </p>
    </article>

