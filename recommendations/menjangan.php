      <article class="prose prose-invert max-w-none">
        <p>Far from the vibrant energy of south Bali lies a tranquil underwater haven: Menjangan Island. As a protected part of the West Bali National Park (Taman Nasional Bali Barat), its reefs have been shielded from over-development and destructive fishing, resulting in some of the healthiest and most diverse coral ecosystems in Bali. Known primarily for its spectacular wall diving, Menjangan is where clarity, colour, and calm converge.</p>

        
        <h3><i class="fa-solid fa-check-double mr-2 text-gold"></i>Key Highlights for Your Dive Plan</h3>
        <ul class="marker:text-gold">
          <li><strong>Pristine Wall Dives:</strong> Menjangan is famed for its spectacular vertical walls, dropping to depths of 30–60 meters and covered in a tapestry of gorgonian sea fans, sponges, and soft corals.</li>
          <li><strong>Exceptional Visibility:</strong> The calm, protected waters often deliver visibility exceeding 30 meters, making it a photographer's dream and perfect for appreciating the sheer scale of the underwater topography.</li>
          <li><strong>Rich Biodiversity:</strong> The national park status ensures healthy corals and abundant marine life. Expect to see turtles, reef sharks, pygmy seahorses, and vast schools of fusiliers and anthias.</li>
          <li><strong>Calm Conditions:</strong> Sheltered from the strong currents found elsewhere in Bali, the sites here offer relaxed drift dives suitable for all experience levels, from newly certified divers to seasoned veterans.</li>
        </ul>

        
        <h3>Menjangan's Premier Dive Sites</h3>
        <p>While conditions on the day will determine the final plan, these are the signature sites that make Menjangan a world-class destination.</p>
        
        <div class="my-4 border-l-4 border-gold pl-4">
          <h4 class="font-bold text-lg text-white">POS II</h4>
          <p class="text-white/80">A classic Menjangan experience. This site offers a stunning wall dive that starts just meters from the surface, descending into the deep blue. It’s a fantastic multi-level dive profile, with the upper reef teeming with colourful reef fish and the deeper sections home to large gorgonians and occasional passing reef sharks. <strong>Perfect for:</strong> All levels, photography, classic wall diving.</p>
        </div>

        <div class="my-4 border-l-4 border-gold pl-4">
          <h4 class="font-bold text-lg text-white">Eel Garden</h4>
          <p class="text-white/80">Named for the huge colony of garden eels on its sandy slope, this site transitions from a rich coral wall to a gentle slope. It’s a great spot for macro enthusiasts to hunt for nudibranchs, shrimp, and other critters in the crevices of the wall before drifting over the eel colony. <strong>Perfect for:</strong> Macro life, observing unique behaviours, drift diving.</p>
        </div>

        <div class="my-4 border-l-4 border-gold pl-4">
          <h4 class="font-bold text-lg text-white">Anchor Wreck (Anker Wreck)</h4>
          <p class="text-white/80">Also known as the ‘Kapal Budak’ (Slave Ship), this is a small, 19th-century wooden shipwreck, though little of the vessel remains beyond its anchor and some encrusted timbers. The dive begins on a beautiful wall before leading down to the anchor at around 35 meters. <strong>Perfect for:</strong> Advanced divers, history enthusiasts, deep dives.</p>
        </div>

        
        <h3>Understanding the Conditions: What to Expect</h3>
        <p>Diving at Menjangan is generally a comfortable and rewarding experience. Water temperatures are a pleasant 27-30°C (80-86°F) year-round. Currents are typically mild to non-existent, making it an excellent place to focus on buoyancy, photography, and simply enjoying the scenery without a struggle. Visibility is the star attraction, rarely dropping below 20 meters and often pushing 40 meters or more.</p>

        
        <h3>Planning Your Menjangan Dive Trip</h3>
        <p>Menjangan Island is uninhabited, so all dive trips are day trips originating from the mainland. Most dive operators are based in the nearby towns of Pemuteran or Lovina. A typical day trip involves:</p>
        <ol>
          <li>Morning departure from your resort or dive center.</li>
          <li>A short drive to the harbor, followed by a 30-40 minute boat ride to the island.</li>
          <li>Two dives at different sites around Menjangan, with a surface interval on the boat or a nearby beach.</li>
          <li>Lunch and refreshments are almost always included.</li>
          <li>Return to the mainland in the mid-afternoon.</li>
        </ol>
        <p>Remember that all visitors must pay a national park entrance fee, which is usually included in the price quoted by your dive operator. Always confirm this when booking.</p>

        
